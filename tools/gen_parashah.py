"""Weekly Torah portion table -> data/parashah.json (offline lookup in the app).
Uses pyluach (pip install pyluach; MIT, tested Hebrew calendar). Run in the cloud shell, then copy the JSON over.
Both schedules are stored: Diaspora and Israel. They differ for a few weeks when a second festival day
(diaspora only) falls on Shabbat. Many Reform congregations keep one festival day; ask CBB which it follows.
cbbsb.org (checked 11/01) only says "the weekly Torah portion"; it names no cycle (annual, triennial, Israel or Diaspora).
Spot-checked: 2026-10-10 Bereshit, 2026-10-31 Vayera, 2027-06-12 diaspora Shavuot / Israel Nasso.
Usage: python tools/gen_parashah.py [out_path]"""
import datetime as dt, json, sys
from pyluach import dates, parshios

NAMES = ["Bereshit", "Noach", "Lech Lecha", "Vayera", "Chayei Sara", "Toldot", "Vayetzei", "Vayishlach", "Vayeshev", "Miketz",
  "Vayigash", "Vayechi", "Shemot", "Vaera", "Bo", "Beshalach", "Yitro", "Mishpatim", "Terumah", "Tetzaveh", "Ki Tisa",
  "Vayakhel", "Pekudei", "Vayikra", "Tzav", "Shmini", "Tazria", "Metzora", "Achrei Mot", "Kedoshim", "Emor", "Behar",
  "Bechukotai", "Bamidbar", "Nasso", "Beha'alotcha", "Sh'lach", "Korach", "Chukat", "Balak", "Pinchas", "Matot", "Masei",
  "Devarim", "Vaetchanan", "Eikev", "Re'eh", "Shoftim", "Ki Teitzei", "Ki Tavo", "Nitzavim", "Vayeilech", "Ha'azinu", "V'Zot HaBerachah"]
BOOKS = [(0, "Genesis"), (12, "Exodus"), (23, "Leviticus"), (33, "Numbers"), (43, "Deuteronomy")]
HOL = {"Rosh Hashana": "Rosh Hashanah", "Yom Kippur": "Yom Kippur", "Succos": "Sukkot", "Shmini Atzeres": "Shemini Atzeret",
  "Simchas Torah": "Simchat Torah", "Pesach": "Passover", "Shavuos": "Shavuot", "Chanuka": "Hanukkah", "Purim": "Purim"}

def book(i): return [b for start, b in BOOKS if i >= start][-1]

def main(out):
    d = dt.date(2026, 10, 1)
    d += dt.timedelta((5 - d.weekday()) % 7)  # first Saturday
    weeks = []
    while d <= dt.date(2031, 12, 31):
        g = dates.GregorianDate(d.year, d.month, d.day)
        dia, isr = parshios.getparsha(g), parshios.getparsha(g, israel=True)
        hol = g.to_heb().holiday()
        row = {"d": d.isoformat(), "dia": dia, "isr": isr}
        if (dia is None or isr is None) and hol: row["hol"] = HOL.get(hol, hol)
        weeks.append(row)
        d += dt.timedelta(7)
    json.dump({"source": "pyluach (Hebrew calendar library), generated by tools/gen_parashah.py",
               "names": NAMES, "books": [book(i) for i in range(len(NAMES))], "weeks": weeks},
              open(out, "w", encoding="utf-8", newline="\n"), ensure_ascii=False, separators=(",", ":"))
    print(out, len(weeks), "Shabbatot;", sum(r["dia"] != r["isr"] for r in weeks), "differ Diaspora/Israel")

if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "data/parashah.json")
